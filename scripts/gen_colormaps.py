#!/usr/bin/env python3
"""Generate src/data/gibsColormaps.ts from the official GIBS colormap XMLs in scripts/colormaps/
(downloaded from https://gibs.earthdata.nasa.gov/colormaps/v1.0/<Layer>.xml)."""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def entries(name):
    xml = open(os.path.join(ROOT, 'scripts', 'colormaps', f'{name}.xml')).read()
    return [(int(m[1]), int(m[2]), int(m[3]), m[4] == 'true', m[5], m[6]) for m in re.finditer(
        r'rgb="(\d+),(\d+),(\d+)" transparent="(\w+)"(?: value="([^"]*)")? label="([^"]*)"', xml)]
def rng(v):
    m = re.match(r'\[(-?[\d.]+),(-?[\d.]+|\+INF)\)', v)
    lo = float(m[1]); hi = lo + 200 if m[2] == '+INF' else float(m[2])
    return (lo + hi) / 2
key = lambda r, g, b: (r << 16) | (g << 8) | b
dem = [(key(r, g, b), round(rng(v), 1)) for r, g, b, t, v, l in entries('ASTER_GDEM_Color_Index') if not t]
slide = [(key(r, g, b), i, l) for i, (r, g, b, t, v, l) in enumerate([e for e in entries('NDH_Landslide_Hazard_Distribution_2000') if not e[3]])]
water = [key(r, g, b) for r, g, b, t, v, l in entries('MODIS_Water_Mask') if not t]
out = ['/* Generated by scripts/gen_colormaps.py from official NASA GIBS colormaps — do not edit. */', '',
       '/** ASTER GDEM colour index: rgb (0xRRGGBB) → elevation in metres (bin midpoint). */',
       'export const DEM_COLORS: [number, number][] = ' + repr([list(x) for x in dem]).replace(' ', '') + ';', '',
       '/** NASA NDH landslide hazard: rgb → class index (0 = negligible … highest) and label. */',
       'export const LANDSLIDE_COLORS: [number, number, string][] = [', *[f"  [{k}, {i}, '{l}']," for k, i, l in slide], '];', '',
       '/** MODIS water mask: rgb of water pixels (land is transparent). */',
       f'export const WATER_COLORS: number[] = {water};', '']
open(os.path.join(ROOT, 'src', 'data', 'gibsColormaps.ts'), 'w').write('\n'.join(out))
print(len(dem), 'DEM colours,', len(slide), 'landslide classes,', len(water), 'water colours')
